        orig, new, touched = _apply(path, ops, inserts, tag)
        n_sub = sum(len(s) for _, s in ops)
        print("[%s] %s" % (tag, os.path.relpath(path, PROJ)))
        print("  · 定点替换行数 = %d · 替换串数 = %d · 追加行数 = %d"
              % (len(touched), n_sub, len(inserts)))
        print("  · 改前字节 = %d · 改后字节 = %d" % (len(orig.encode()), len(new.encode())))
        plans.append((path, orig, new, bak))
