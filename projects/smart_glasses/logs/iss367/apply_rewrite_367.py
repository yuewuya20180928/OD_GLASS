def _apply(path, ops, inserts, tag):
    with open(path, encoding="utf-8") as fh:
        orig = fh.read()
    lines = orig.split("\n")
    touched = set()
    for ln, subs in ops:
        idx = ln - 1
        if idx < 0 or idx >= len(lines):
            raise AssertionError("%s: 行号 %d 越界" % (tag, ln))
        cur = lines[idx]
        for old, new in subs:
            if old not in cur:
                raise AssertionError("%s: 第 %d 行找不到待改串 %r\n    该行 = %r" % (tag, ln, old, cur))
            if cur.count(old) != 1:
                raise AssertionError("%s: 第 %d 行待改串出现 %d 次 (必须恰好 1 次)"
                                     % (tag, ln, cur.count(old)))
            cur = cur.replace(old, new, 1)
        if cur == lines[idx]:
            raise AssertionError("%s: 第 %d 行改完没变" % (tag, ln))
        lines[idx] = cur
        touched.add(ln)
    # 追加行 (★按原始行号插入, 最后统一做, 避免行号漂移★)
    for ln, text in inserts:
        idx = ln - 1
        if idx < 0 or idx >= len(lines):
            raise AssertionError("%s: 插入锚点行号 %d 越界" % (tag, ln))
        lines.insert(idx + 1, text)
    return orig, "\n".join(lines), sorted(touched)


