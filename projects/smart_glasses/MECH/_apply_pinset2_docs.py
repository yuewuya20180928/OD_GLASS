def atomic_write(path: str, text: str) -> None:
    d = os.path.dirname(path) or "."
    fd, tmp = tempfile.mkstemp(prefix=os.path.basename(path) + ".", suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def main() -> int:
    dry = "--dry-run" in sys.argv
    total_applied = 0
    total_skipped = 0
    for fname, pairs in EDITS.items():
        path = os.path.join(HERE, fname)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        orig = text
        applied = skipped = 0
        for i, (old, new) in enumerate(pairs, 1):
            # ★ 幂等顺序很关键: 先查 "新文本在不在" —— 因为有 4 条替换满足 old ⊂ new
            #   (新文本 = 老文本 + 追加行), 若先查 old 会每次都再套一层 ⇒ 重复插入。
            if new in text:
                skipped += 1          # 幂等: 已经改过了
            elif old in text:
                text = text.replace(old, new, 1)
                applied += 1
            else:
                print(f"❌ {fname} 第 {i} 条替换: 老文本找不到 (且新文本也不在) —— 中止, 不落盘")
                return 2
        total_applied += applied
        total_skipped += skipped
        if applied == 0:
            print(f"  ✅ {fname}: 已是新版 (跳过 {skipped} 条)")
            continue
        if dry:
            print(f"  [dry-run] {fname}: 将改 {applied} 条 (跳过 {skipped})")
            continue
        atomic_write(path, text)
        print(f"  ✅ {fname}: 已改 {applied} 条 (跳过 {skipped}), 字节 {len(orig)} → {len(text)}")
    print(f"\n合计: 改 {total_applied} 条 / 跳过 {total_skipped} 条")
    if dry:
        print("[dry-run] 未落盘")
    return 0


if __name__ == "__main__":
    sys.exit(main())
