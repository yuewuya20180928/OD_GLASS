CAP_NOBRIDGE = 340   # mAh 无桥档电芯 (Renata ICP582035PR-01) [官网]
CHG_EFF = 0.83       # 充电效率 —— ★只用于选电芯, 不用于放电续航
P_COEF_B = 1.0 / (V_BAT * CHG_EFF * DOD) * 1000   # = 361.81 mAh per (W·h)

# 四档功耗 (来自 HW/POWER_SHUTDOWN_V3.md §6 / POWER_BUDGET_V3.md)
